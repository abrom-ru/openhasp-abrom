# Pre-build script: embed embed/fonts/*.bin into the firmware partition and
# generate a name -> blob registry in src/hasp_embed_fonts.cpp.
#
# Enable per env in platformio_override.ini:
#   extra_scripts =
#       ${esp32.extra_scripts}
#       pre:tools/embed_fonts_register.py
#
# On boot filesystemSetupFiles() copies each font to /<name> on LittleFS
# (rewritten when the size differs), where hasp_font_load() picks it up.

Import("env")

import glob
import os
import re

EMBED_DIR = "embed/fonts"
OUT_FILE = os.path.join("src", "hasp_embed_fonts.cpp")


def to_sym(rel_path):
    rel_path = rel_path.replace("\\", "/")
    return "_binary_" + re.sub(r"[^A-Za-z0-9]", "_", rel_path)


files = sorted(glob.glob(os.path.join(EMBED_DIR, "*.bin")))

if files:
    rel_files = [f.replace("\\", "/") for f in files]
    env.Append(CPPDEFINES=["HASP_USE_EMBED_FONTS"])

    # Append our files to board_build.embed_files for the current env so the
    # platform's _embed_files.py picks them up (it reads via GetProjectOption).
    config = env.GetProjectConfig()
    section = "env:" + env["PIOENV"]
    existing = env.GetProjectOption("board_build.embed_files", "") or ""
    parts = [p for p in (existing.splitlines() if isinstance(existing, str) else list(existing)) if p.strip()]
    parts.extend(rel_files)
    config.set(section, "board_build.embed_files", "\n".join(parts))

lines = []
lines.append("// AUTO-GENERATED by tools/embed_fonts_register.py - do not edit")
lines.append('#include "hasp_embed_fonts.h"')
lines.append("")
lines.append("#ifdef HASP_USE_EMBED_FONTS")
lines.append("")
for f in files:
    sym = to_sym(f)
    lines.append('extern const uint8_t {0}_start[] asm("{0}_start");'.format(sym))
    lines.append('extern const uint8_t {0}_end[]   asm("{0}_end");'.format(sym))
lines.append("")
lines.append("namespace {")
lines.append("struct EmbedFont { const char* name; const uint8_t* start; const uint8_t* end; };")
lines.append("const EmbedFont kEmbedFonts[] = {")
for f in files:
    base = os.path.basename(f)
    sym = to_sym(f)
    lines.append('    {{ "/{0}", {1}_start, {1}_end }},'.format(base, sym))
lines.append("};")
lines.append("} // namespace")
lines.append("")
lines.append('extern "C" size_t hasp_embed_font_count(void) {')
lines.append("    return sizeof(kEmbedFonts) / sizeof(kEmbedFonts[0]);")
lines.append("}")
lines.append("")
lines.append('extern "C" const uint8_t* hasp_embed_font_get(size_t i, const char** name, size_t* len) {')
lines.append("    if (i >= hasp_embed_font_count()) return nullptr;")
lines.append("    if (name) *name = kEmbedFonts[i].name;")
lines.append("    if (len) *len = (size_t)(kEmbedFonts[i].end - kEmbedFonts[i].start);")
lines.append("    return kEmbedFonts[i].start;")
lines.append("}")
lines.append("#else")
lines.append('extern "C" size_t hasp_embed_font_count(void) { return 0; }')
lines.append('extern "C" const uint8_t* hasp_embed_font_get(size_t, const char**, size_t*) { return nullptr; }')
lines.append("#endif")
lines.append("")

new_content = "\n".join(lines)

existing = ""
if os.path.exists(OUT_FILE):
    with open(OUT_FILE, "r") as fh:
        existing = fh.read()

if existing != new_content:
    with open(OUT_FILE, "w") as fh:
        fh.write(new_content)
    print("[embed_fonts] wrote {0} ({1} entries)".format(OUT_FILE, len(files)))
else:
    print("[embed_fonts] {0} up to date ({1} entries)".format(OUT_FILE, len(files)))
